#!/usr/bin/env bash
# Generate kas-local.yml that reuses already-cloned Yocto layers.
# Run this inside the UTM VM once — then build with:
#   kas build kas.yml:kas-local.yml
#
# Usage:
#   bash scripts/use-local-layers.sh /path/to/existing/layers
#
# Example (if another project already has the layers at ~/yocto/other-project/):
#   bash scripts/use-local-layers.sh ~/yocto/other-project
#
# The script auto-detects poky / meta-raspberrypi / meta-openembedded inside
# the given directory and writes kas-local.yml next to kas.yml.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTPUT="${REPO_ROOT}/kas-local.yml"

# ---- argument handling -------------------------------------------------------
LAYERS_DIR="${1:-}"
if [[ -z "${LAYERS_DIR}" ]]; then
    echo "Usage: bash scripts/use-local-layers.sh <path-to-existing-layers>"
    echo ""
    echo "Example:"
    echo "  bash scripts/use-local-layers.sh ~/yocto/other-project"
    echo ""
    echo "The directory must contain at least one of:"
    echo "  poky/  meta-raspberrypi/  meta-openembedded/"
    exit 1
fi

LAYERS_DIR="$(realpath "${LAYERS_DIR}")"

if [[ ! -d "${LAYERS_DIR}" ]]; then
    echo "ERROR: Directory not found: ${LAYERS_DIR}"
    exit 1
fi

# ---- detect layer paths ------------------------------------------------------
find_layer() {
    local name="$1"
    # Try the directory itself, then one level deeper
    if [[ -d "${LAYERS_DIR}/${name}" ]]; then
        echo "${LAYERS_DIR}/${name}"
        return
    fi
    # Also look for common naming variations
    for variant in "${name}" "${name/-/_}" "${name/_/-}"; do
        for candidate in "${LAYERS_DIR}/${variant}" "${LAYERS_DIR}/"*"${variant}"*; do
            if [[ -d "${candidate}/.git" ]] || [[ -d "${candidate}/conf" ]]; then
                echo "${candidate}"
                return
            fi
        done
    done
    echo ""
}

POKY_PATH=$(find_layer "poky")
MRPI_PATH=$(find_layer "meta-raspberrypi")
MOEOE_PATH=$(find_layer "meta-openembedded")

echo "==> Detected layers in ${LAYERS_DIR}:"
echo "    poky              : ${POKY_PATH:-NOT FOUND}"
echo "    meta-raspberrypi  : ${MRPI_PATH:-NOT FOUND}"
echo "    meta-openembedded : ${MOEOE_PATH:-NOT FOUND}"
echo ""

# Warn about missing layers — the build will fail without them
MISSING=0
[[ -z "${POKY_PATH}" ]]  && { echo "WARNING: poky not found — KAS will still fetch it from the internet"; MISSING=1; }
[[ -z "${MRPI_PATH}" ]]  && { echo "WARNING: meta-raspberrypi not found — KAS will still fetch it"; MISSING=1; }
[[ -z "${MOEOE_PATH}" ]] && { echo "WARNING: meta-openembedded not found — KAS will still fetch it"; MISSING=1; }
[[ "${MISSING}" -eq 1 ]] && echo ""

# Verify Scarthgap branch for each found layer
check_branch() {
    local path="$1"
    local name="$2"
    if [[ -d "${path}/.git" ]]; then
        local branch
        branch=$(git -C "${path}" symbolic-ref --short HEAD 2>/dev/null || git -C "${path}" describe --tags --exact-match 2>/dev/null || echo "unknown")
        if [[ "${branch}" != *"scarthgap"* ]]; then
            echo "WARNING: ${name} is on branch '${branch}', not 'scarthgap'."
            echo "         This project requires Scarthgap.  Switch with:"
            echo "           git -C ${path} checkout scarthgap"
            echo ""
        else
            echo "    [OK] ${name} is on scarthgap"
        fi
    fi
}

[[ -n "${POKY_PATH}" ]]  && check_branch "${POKY_PATH}"  "poky"
[[ -n "${MRPI_PATH}" ]]  && check_branch "${MRPI_PATH}"  "meta-raspberrypi"
[[ -n "${MOEOE_PATH}" ]] && check_branch "${MOEOE_PATH}" "meta-openembedded"
echo ""

# ---- write kas-local.yml -----------------------------------------------------
echo "==> Writing ${OUTPUT} ..."

cat > "${OUTPUT}" << YAML
header:
  version: 14

# Generated by scripts/use-local-layers.sh on $(date '+%Y-%m-%d')
# Reuses existing layer clones — KAS will not re-fetch these repos.
# Build with: kas build kas.yml:kas-local.yml
# This file is gitignored (machine-specific).

repos:
YAML

if [[ -n "${POKY_PATH}" ]]; then
cat >> "${OUTPUT}" << YAML
  poky:
    path: ${POKY_PATH}
    layers:
      meta:
      meta-poky:
      meta-yocto-bsp:

YAML
fi

if [[ -n "${MRPI_PATH}" ]]; then
cat >> "${OUTPUT}" << YAML
  meta-raspberrypi:
    path: ${MRPI_PATH}
    layers:
      .:

YAML
fi

if [[ -n "${MOEOE_PATH}" ]]; then
cat >> "${OUTPUT}" << YAML
  meta-openembedded:
    path: ${MOEOE_PATH}
    layers:
      meta-oe:
      meta-networking:
      meta-python:

YAML
fi

echo ""
echo "==> Done.  kas-local.yml written."
echo ""
echo "Next step — build:"
echo "  kas build kas.yml:kas-local.yml"
echo ""
echo "If you see a branch mismatch warning above, switch the affected"
echo "layer to scarthgap before building."
