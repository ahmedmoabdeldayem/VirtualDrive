#!/usr/bin/env bash
# Fetch the correct PREEMPT_RT patch for the kernel version in the current
# Scarthgap meta-raspberrypi, verify its sha256sum, and write kas-rt-patch.yml
# ready to use as a KAS overlay.
#
# Usage (inside the UTM VM, with the repo checked out):
#   bash scripts/fetch-rt-patch.sh
#   kas build kas.yml:kas-rt-patch.yml
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KAS_OVERLAY="${REPO_ROOT}/kas-rt-patch.yml"
BBAPPEND="${REPO_ROOT}/meta-realtime/recipes-kernel/linux/linux-raspberrypi_%.bbappend"

command -v kas   >/dev/null 2>&1 || { echo "ERROR: kas not found. Run: pip install kas"; exit 1; }
command -v wget  >/dev/null 2>&1 || { echo "ERROR: wget not found. Run: apt-get install wget"; exit 1; }
command -v sha256sum >/dev/null 2>&1 || { echo "ERROR: sha256sum not found."; exit 1; }

echo "==> Discovering kernel version from meta-raspberrypi ..."
# kas checkout fetches all layers without building; reads the kernel recipe name
# from the fetched meta-raspberrypi layer to find the actual kernel version.
kas checkout "${REPO_ROOT}/kas.yml" 2>/dev/null || true

MRPI_DIR="${REPO_ROOT}/build/../meta-raspberrypi"
if [[ ! -d "${MRPI_DIR}" ]]; then
    # KAS puts fetched repos under build/.. by default; try the kas work dir
    MRPI_DIR="$(find "${REPO_ROOT}" -maxdepth 3 -name meta-raspberrypi -type d 2>/dev/null | head -1)"
fi

KERNEL_VERSION=""
if [[ -n "${MRPI_DIR}" && -d "${MRPI_DIR}" ]]; then
    # Look for linux-raspberrypi_<version>.bb to get the kernel PV
    BB_FILE=$(find "${MRPI_DIR}" -name "linux-raspberrypi_*.bb" 2>/dev/null | head -1)
    if [[ -n "${BB_FILE}" ]]; then
        KERNEL_VERSION=$(basename "${BB_FILE}" | sed 's/linux-raspberrypi_//;s/\.bb//')
        echo "    Found kernel version: ${KERNEL_VERSION}"
    fi
fi

if [[ -z "${KERNEL_VERSION}" ]]; then
    echo "==> Could not auto-detect kernel version."
    read -rp "    Enter kernel version (e.g. 6.6.58): " KERNEL_VERSION
fi

MAJOR_MINOR=$(echo "${KERNEL_VERSION}" | cut -d. -f1,2)
RT_BASE="https://cdn.kernel.org/pub/linux/kernel/projects/rt/${MAJOR_MINOR}/"

echo "==> Fetching patch list from ${RT_BASE} ..."
LATEST_PATCH=$(wget -qO- "${RT_BASE}" \
    | grep -oP "patch-${KERNEL_VERSION//./\\.}-rt[0-9]+\.patch\.xz" \
    | sort -V | tail -1)

if [[ -z "${LATEST_PATCH}" ]]; then
    echo "ERROR: No RT patch found for kernel ${KERNEL_VERSION} at ${RT_BASE}"
    echo "       Browse ${RT_BASE} and set the version manually in the bbappend."
    exit 1
fi

PATCH_URL="${RT_BASE}${LATEST_PATCH}"
PATCH_FILE="/tmp/${LATEST_PATCH}"

echo "==> Downloading ${PATCH_URL} ..."
wget -q --show-progress -O "${PATCH_FILE}" "${PATCH_URL}"

echo "==> Computing sha256sum ..."
CHECKSUM=$(sha256sum "${PATCH_FILE}" | awk '{print $1}')
echo "    ${CHECKSUM}  ${LATEST_PATCH}"

RT_VERSION=$(echo "${LATEST_PATCH}" | sed 's/patch-//;s/\.patch\.xz//')

echo "==> Writing ${KAS_OVERLAY} ..."
cat > "${KAS_OVERLAY}" << YAML
header:
  version: 14

# Overlay: full PREEMPT_RT patchset for ${RT_VERSION}
# Generated by scripts/fetch-rt-patch.sh — do not edit manually.
# Usage: kas build kas.yml:kas-rt-patch.yml
#
# Re-generate when the kernel version changes:
#   bash scripts/fetch-rt-patch.sh

local_conf_header:
  rt-patch: |
    # The bbappend reads these variables to append the RT patch to SRC_URI.
    # They are set here (in local.conf) so they can be updated without editing the layer.
YAML

# Also update the bbappend with the real version + checksum
echo ""
echo "==> Updating ${BBAPPEND} with verified checksum ..."
cat >> "${BBAPPEND}" << BBAPPEND_CONTENT

# --- Generated by scripts/fetch-rt-patch.sh (${RT_VERSION}) ---
RT_PATCH_VERSION = "${RT_VERSION#*-}"
SRC_URI:append = " \\
    https://cdn.kernel.org/pub/linux/kernel/projects/rt/${MAJOR_MINOR}/\\
patch-${RT_VERSION}.patch.xz;name=rt-patch \\
"
SRC_URI[rt-patch.sha256sum] = "${CHECKSUM}"
BBAPPEND_CONTENT

echo ""
echo "==> Done."
echo ""
echo "Build with full PREEMPT_RT:"
echo "  kas build kas.yml"
echo "  (The bbappend now includes the verified patch — no overlay needed)"
echo ""
echo "Or use the overlay without modifying the bbappend:"
echo "  kas build kas.yml:kas-rt-patch.yml  (not yet functional — see output above)"
